/**
 * Generates src/app/theme.css: CSS variables for light and dark mode.
 * Tailwind's colours are mapped to these variables (see tailwind.config.ts), so every existing class
 * (bg-white, text-slate-900, bg-rose-50...) switches theme automatically.
 *
 *  - slate (neutrals): light = Tailwind's slate. Dark = a hand-tuned neutral near-black scale (like the reference theme).
 *  - accent ramps (rose, amber, ...): dark = the same ramp mirrored (50 <-> 950, 100 <-> 900 ...), so light tints become
 *    dark tints and dark text becomes light text.
 *
 * Run: npm run gen:theme   (only needed when changing the palette)
 */
import { writeFileSync } from "node:fs";
import colors from "tailwindcss/colors.js";

const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
export const ACCENTS = ["rose", "amber", "red", "emerald", "sky", "indigo", "violet", "orange", "teal", "cyan", "green", "blue"];

const rgb = (hex) => {
  const h = hex.replace("#", "");
  return `${parseInt(h.slice(0, 2), 16)} ${parseInt(h.slice(2, 4), 16)} ${parseInt(h.slice(4, 6), 16)}`;
};

// Dark neutrals (index follows SHADES): near-black canvas, cards slightly lighter, subtle borders, high-contrast text.
const DARK_SLATE = ["24 24 27", "32 32 36", "42 42 48", "58 58 66", "113 113 122", "140 140 150", "168 168 178", "196 196 204", "224 224 230", "244 244 247", "250 250 252"];

let light = "";
let dark = "";

for (const name of ["slate", ...ACCENTS]) {
  SHADES.forEach((shade, i) => {
    light += `  --c-${name}-${shade}: ${rgb(colors[name][shade])};\n`;
    const darkValue = name === "slate" ? DARK_SLATE[i] : rgb(colors[name][SHADES[SHADES.length - 1 - i]]);
    dark += `  --c-${name}-${shade}: ${darkValue};\n`;
  });
}

const css = `/* GENERATED by scripts/gen-theme.mjs. Do not edit by hand. */
:root {
${light}  --c-white: 255 255 255;
  --c-canvas: 244 246 250;
  --c-ink: 15 28 63;
  --c-ink-soft: 30 45 85;
  /* chart colours stay the same brightness in both themes */
  --chart-high: 244 63 94;
  --chart-medium: 245 158 11;
  --chart-low: 148 163 184;
  --chart-accent: 99 102 241;
  --shadow-card: 0 1px 2px rgb(15 28 63 / 0.05), 0 0 0 1px rgb(15 28 63 / 0.06);
  --shadow-lift: 0 6px 16px -4px rgb(15 28 63 / 0.14), 0 0 0 1px rgb(15 28 63 / 0.08);
  color-scheme: light;
}

:root.dark {
${dark}  --c-white: 17 17 20;
  --c-canvas: 9 9 11;
  --c-ink: 244 244 247;
  --c-ink-soft: 224 224 232;
  --shadow-card: 0 0 0 1px rgb(255 255 255 / 0.07);
  --shadow-lift: 0 10px 28px -8px rgb(0 0 0 / 0.7), 0 0 0 1px rgb(255 255 255 / 0.12);
  color-scheme: dark;
}
`;

writeFileSync("src/app/theme.css", css);
console.log(`Wrote src/app/theme.css (${css.split("\n").length} lines)`);
